class Report:
    def __init__(self) -> None:
        self.errors: list[str] = []
        self.warnings: list[str] = []
        self.info: list[str] = []
    def error(self, message: str) -> None: self.errors.append(message)
    def warn(self, message: str) -> None: self.warnings.append(message)
    def ok(self, message: str) -> None: self.info.append(message)
    @property
    def passed(self) -> bool: return not self.errors
    def as_dict(self) -> dict[str, Any]:
        return {'checker':'ARGON assurance-pack structural/readiness checker','scope_warning':'A passing structural check is not verification of the ARGON product.', 'passed':self.passed,'error_count':len(self.errors),'warning_count':len(self.warnings),'errors':self.errors,'warnings':self.warnings,'info':self.info}

def read_csv(root: Path, relative: Path, required_fields: list[str], report: Report, optional_fields: list[str] | None = None) -> list[dict[str, str]]:
    path = root / relative
    if not path.is_file():
        report.error(f'Missing required register: {relative.as_posix()}')
        return []
    try:
        with path.open('r', newline='', encoding='utf-8-sig') as f:
            reader = csv.DictReader(f)
            fields = reader.fieldnames or []
            missing = [field for field in required_fields if field not in fields]
            if missing:
                report.error(f'{relative.as_posix()}: missing CSV columns: {", ".join(missing)}')
                return []
            rows = []
            for line, row in enumerate(reader, start=2):
                # Normalize None values generated by malformed trailing delimiters.
                clean = {k: (v or '').strip() for k, v in row.items() if k is not None}
                for extra in optional_fields or []:
                    clean.setdefault(extra, '')
                if not any(clean.values()):
                    continue
                clean['__line__'] = str(line)
                rows.append(clean)
            report.ok(f'{relative.as_posix()}: read {len(rows)} data row(s)')
            return rows
    except (OSError, UnicodeError, csv.Error) as exc:
        report.error(f'{relative.as_posix()}: cannot read CSV: {exc}')
        return []

def unique_ids(rows: list[dict[str, str]], key: str, label: str, report: Report) -> dict[str, dict[str, str]]:
    result: dict[str, dict[str, str]] = {}
    for row in rows:
        value = row.get(key, '').strip()
        line = row.get('__line__', '?')
        if not value:
            report.error(f'{label} line {line}: empty {key}')
        elif value in result:
            report.error(f'{label} line {line}: duplicate {key} {value!r} (first at line {result[value].get("__line__", "?")})')
        else:
            result[value] = row
    return result

def date_value(value: str) -> dt.date | None:
    """Strict YYYY-MM-DD only. Longer text (timestamps, trailing words) is rejected, never truncated."""
    if not value or not ISO_DATE.fullmatch(value):
        return None
    try:
        return dt.date.fromisoformat(value)
    except ValueError:
        return None

def parse_timestamp(value: str) -> dt.datetime | None:
    if not value:
        return None
    try:
        parsed = dt.datetime.fromisoformat(value.replace('Z', '+00:00'))
    except ValueError:
        return None
    if parsed.tzinfo is None or parsed.utcoffset() is None:
        return None
    return parsed

def valid_timestamp(value: str) -> bool:
    return parse_timestamp(value) is not None

def artifact_path(root: Path, raw: str, report: Report, context: str, required: bool) -> Path | None:
    if not raw:
        if required:
            report.error(f'{context}: artifact_path is required for this evidence state')
        return None
    p = Path(raw)
    if p.is_absolute():
        report.error(f'{context}: artifact_path must be repository-relative, not absolute')
        return None
    candidate = (root / p).resolve()
    root_resolved = root.resolve()
    try:
        candidate.relative_to(root_resolved)
    except ValueError:
        report.error(f'{context}: artifact_path escapes repository root')
        return None
    if required and not candidate.is_file():
        report.error(f'{context}: artifact file does not exist: {raw}')
        return None
    return candidate

def check_markdown_links(root: Path, report: Report) -> None:
    base = root / 'docs/assurance'
    if not base.is_dir():
        return
    pattern = re.compile(r'\[[^\]]*\]\(([^)]+)\)')
    count = 0
    for md in base.rglob('*.md'):
        try:
            text = md.read_text(encoding='utf-8')
        except (OSError, UnicodeError) as exc:
            report.error(f'{md.relative_to(root)}: cannot read Markdown: {exc}')
            continue
        for raw_target in pattern.findall(text):
            target = raw_target.strip().split()[0].strip('<>')
            if not target or target.startswith(('#', 'http://', 'https://', 'mailto:', 'tel:')):
                continue
            target = target.split('#', 1)[0]
            if not target:
                continue
            count += 1
            candidate = (md.parent / target).resolve()
            try:
                candidate.relative_to(root.resolve())
            except ValueError:
                report.error(f'{md.relative_to(root)}: local link escapes repository: {raw_target}')
                continue
            if not candidate.exists():
                report.error(f'{md.relative_to(root)}: broken local link: {raw_target}')
    report.ok(f'Checked {count} local Markdown link(s) under docs/assurance')

def linked_controls(risk: dict[str, str]) -> list[str]:
    return [x.strip() for x in risk.get('linked_controls', '').split(';') if x.strip()]

def evidence_is_current(evidence: dict[str, str] | None, today: dt.date) -> bool:
    if not evidence or evidence.get('status') != 'ACCEPTED':
        return False
    valid_until = date_value(evidence.get('valid_until', ''))
    return valid_until is not None and valid_until >= today

def valid_accepted_risk(risk: dict[str, str] | None, today: dt.date, evidence_by_id: dict[str, dict[str, str]]) -> bool:
    if not risk or risk.get('status') != 'ACCEPTED' or not risk.get('accepted_by'):
        return False
    expiry = date_value(risk.get('expires_on', ''))
    evidence = evidence_by_id.get(risk.get('acceptance_evidence_id', ''))
    return (expiry is not None and expiry >= today and evidence_is_current(evidence, today)
            and evidence.get('control_id') in linked_controls(risk))

def resolve_commit(root: Path, sha: str) -> bool:
    """True only if `sha` (already format-checked, full length) names a commit object in the repository at `root`."""
    try:
        result = subprocess.run(['git', '-C', str(root), 'rev-parse', '--verify', '--quiet', f'{sha}^{{commit}}'],
                                capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return False
    return result.returncode == 0 and result.stdout.strip().lower() == sha.lower()

def check_release_manifest(root: Path, s: dict[str, str], report: Report, prefix: str) -> Path | None:
    """The digest must be the SHA-256 of a real release manifest that itself names this release and commit."""
    raw = s.get('release_artifact_path', '')
    if not raw:
        report.error(f'{prefix}release_artifact_path is required: artifact_digest must be tied to a release artifact/manifest file')
        return None
    path = artifact_path(root, raw, report, f'{prefix}release artifact', required=True)
    if path is None:
        return None
    if HEX_SHA256.fullmatch(s.get('artifact_digest', '')) and hashlib.sha256(path.read_bytes()).hexdigest().lower() != s['artifact_digest'].lower():
        report.error(f'{prefix}artifact_digest does not match the SHA-256 of release_artifact_path ({raw})')
        return path
    try:
        manifest = json.loads(path.read_text(encoding='utf-8'))
    except (OSError, UnicodeError, ValueError) as exc:
        report.error(f'{prefix}release manifest {raw} is not readable JSON: {exc}')
        return path
    if not isinstance(manifest, dict):
        report.error(f'{prefix}release manifest {raw} must be a JSON object')
        return path
    if manifest.get('release_id') != s.get('release_id'):
        report.error(f'{prefix}release manifest {raw} must declare release_id equal to {s.get("release_id")!r}')
    if str(manifest.get('commit_sha', '')).lower() != s.get('commit_sha', '').lower():
        report.error(f'{prefix}release manifest {raw} must declare commit_sha equal to the sign-off commit_sha')
    if 'environment' in manifest and str(manifest['environment']).lower() != s.get('environment', '').lower():
        report.error(f'{prefix}release manifest {raw} declares a different environment')
    return path

def check_rollback_plan(root: Path, s: dict[str, str], report: Report, prefix: str) -> Path | None:
    """A dedicated, structured rollback plan for this release. File existence alone is not accepted."""
    raw = s.get('rollback_plan_path', '')
    path = artifact_path(root, raw, report, f'{prefix}rollback plan', required=True)
    if path is None:
        return None
    if path.suffix.lower() != '.md':
        report.error(f'{prefix}rollback plan {raw} must be a Markdown (.md) file with the documented structure')
        return path
    try:
        text = path.read_text(encoding='utf-8')
    except (OSError, UnicodeError) as exc:
        report.error(f'{prefix}rollback plan {raw} cannot be read: {exc}')
        return path
    declared = {m.group(1).lower(): m.group(2) for m in re.finditer(r'^(release_id|environment|commit_sha):[ \t]*(\S+)[ \t]*$', text, re.MULTILINE)}
    expected = {'release_id': s.get('release_id', ''), 'environment': s.get('environment', '').lower(), 'commit_sha': s.get('commit_sha', '').lower()}
    for key, want in expected.items():
        got = declared.get(key, '')
        if key != 'release_id':
            got = got.lower()
        if got != want:
            report.error(f'{prefix}rollback plan {raw} must declare {key}: {want} (found {got or "nothing"}); a generic policy file is not a release rollback plan')
    headings = list(re.finditer(r'^#{1,6}[ \t]+(.+?)[ \t]*$', text, re.MULTILINE))
    for name in ROLLBACK_SECTIONS:
        index = next((i for i, h in enumerate(headings) if h.group(1).strip().lower() == name.lower()), None)
        if index is None:
            report.error(f'{prefix}rollback plan {raw} is missing required section: {name!r}')
            continue
        end = headings[index + 1].start() if index + 1 < len(headings) else len(text)
        body = ' '.join(text[headings[index].end():end].split())
        if not body or PLACEHOLDER.fullmatch(body):
            report.error(f'{prefix}rollback plan {raw}: section {name!r} is empty or a placeholder')
    return path

def check_g4_signoff(root: Path, s: dict[str, str], report: Report, today: dt.date, prefix: str, as_of: dt.date | None = None) -> bool:
    """Validate one production G4 APPROVE row. Returns True only if this call added no errors.

    as_of=None  -> G4 evaluation today: the approval must be unexpired now.
    as_of=<date> -> G5 look-back: the approval must have been recorded on/before `as_of` and still valid on `as_of`.
    """
    before = len(report.errors)
    fields = ['release_id', 'decision_owner', 'commit_sha', 'artifact_digest', 'configuration_version', 'migration_version', 'scope', 'rollback_plan_path', 'qa_signoff', 'security_signoff', 'clinical_signoff', 'privacy_legal_signoff', 'operations_signoff', 'recorded_utc', 'valid_until']
    missing = [f for f in fields if not s.get(f)]
    if missing:
        report.error(f'{prefix}production sign-off row is missing: {", ".join(missing)}')
        return False
    recorded = parse_timestamp(s['recorded_utc'])
    if recorded is None:
        report.error(f'{prefix}recorded_utc must be ISO-8601 with timezone')
    else:
        recorded_date = recorded.astimezone(dt.timezone.utc).date()
        if recorded_date > today:
            report.error(f'{prefix}recorded_utc is in the future')
        if as_of is not None and recorded_date > as_of:
            report.error(f'{prefix}production sign-off was recorded after period_start ({as_of.isoformat()}), so it cannot precede that operating period')
    expiry = date_value(s['valid_until'])
    if as_of is None:
        if expiry is None or expiry < today:
            report.error(f'{prefix}production sign-off is expired or has invalid valid_until')
    elif expiry is None:
        report.error(f'{prefix}production sign-off has invalid valid_until (must be YYYY-MM-DD)')
    elif expiry < as_of:
        report.error(f'{prefix}production sign-off is not valid at period_start ({as_of.isoformat()}); valid_until is {expiry.isoformat()}')
    if not HEX_COMMIT.fullmatch(s['commit_sha']):
        report.error(f'{prefix}commit_sha must be a full 40- or 64-character hexadecimal commit id (abbreviated or free text is rejected)')
    elif not resolve_commit(root, s['commit_sha']):
        report.error(f'{prefix}commit_sha does not resolve to a commit in this repository (or git is unavailable)')
    if not HEX_SHA256.fullmatch(s['artifact_digest']):
        report.error(f'{prefix}artifact_digest must be exactly 64 hexadecimal characters (SHA-256, no prefix)')
    manifest = check_release_manifest(root, s, report, prefix)
    plan = check_rollback_plan(root, s, report, prefix)
    if manifest is not None and plan is not None and manifest == plan:
        report.error(f'{prefix}release manifest and rollback plan must be different files')
    names = [s.get(f, '').strip() for f in ['decision_owner', 'qa_signoff', 'security_signoff', 'clinical_signoff', 'privacy_legal_signoff', 'operations_signoff']]
    if len(set(names)) != len(names):
        report.error(f'{prefix}decision owner and signers must be distinct under this conservative default; change only through approved governance')
    ok = len(report.errors) == before
    if ok and as_of is None:
        report.ok(f'{prefix}rollback plan file structure checked for release {s["release_id"]}; this does not prove a rollback drill succeeded (VFY-OPS-003 needs ACCEPTED release-bound evidence)')
    return ok

def check_evidence_binding(ev: dict[str, str], s: dict[str, str], ctx: str, report: Report, historical: bool) -> None:
    """Evidence must belong to the exact release/environment/commit/artifact that the sign-off approved."""
    missing = [f for f in EVIDENCE_OPTIONAL if not ev.get(f)]
    if missing:
        report.error(f'{ctx}: evidence lacks release binding field(s): {", ".join(missing)}')
        return
    if ev['release_id'] != s.get('release_id'):
        report.error(f'{ctx}: evidence is not bound to release {s.get("release_id")!r} (it names {ev["release_id"]!r})')
    if ev['environment'].lower() != s.get('environment', '').lower():
        report.error(f'{ctx}: evidence is not bound to environment {s.get("environment")!r} (it names {ev["environment"]!r})')
    if ev['commit_sha'].lower() != s.get('commit_sha', '').lower():
        report.error(f'{ctx}: evidence is not bound to commit {s.get("commit_sha")} (it names {ev["commit_sha"]})')
    if ev['artifact_digest'].lower() != s.get('artifact_digest', '').lower():
        report.error(f'{ctx}: evidence is not bound to artifact_digest {s.get("artifact_digest")} (it names {ev["artifact_digest"]})')
    if historical:
        return
    created, recorded = parse_timestamp(ev.get('created_utc', '')), parse_timestamp(s.get('recorded_utc', ''))
    if created and recorded and created > recorded:
        report.error(f'{ctx}: evidence was created after the approval was recorded, so the approvers could not have relied on it')
    valid_until = date_value(ev.get('valid_until', ''))
    if valid_until and recorded and valid_until < recorded.astimezone(dt.timezone.utc).date():
        report.error(f'{ctx}: evidence was not valid at the time the approval was recorded')

def check_bound_control_evidence(matrix_by_id: dict[str, dict[str, str]], evidence_by_id: dict[str, dict[str, str]], s: dict[str, str], gate: str, report: Report, historical: bool) -> None:
    for control_id, row in matrix_by_id.items():
        if row.get('required_gate') != 'G4' and control_id not in RELEASE_BOUND_EXTRA_CONTROLS:
            continue
        if row.get('status') not in {'PASS', 'NOT_APPLICABLE'}:
            continue  # the ordinary gate loop already reports these
        ev = evidence_by_id.get(row.get('evidence_id', ''))
        if ev:
            check_evidence_binding(ev, s, f'Gate {gate}: control {control_id} evidence {ev.get("evidence_id")}', report, historical)

def production_approvals(rows: list[dict[str, str]], release_id: str | None) -> list[dict[str, str]]:
    return [r for r in rows if r.get('gate') == 'G4' and r.get('environment', '').lower() == 'production' and r.get('decision') == 'APPROVE'
            and (release_id is None or r.get('release_id') == release_id)]

def validate(root: Path, gate: str | None = None, today: dt.date | None = None, release_id: str | None = None) -> Report:
    report = Report()
    matrix_rows = read_csv(root, MATRIX, MATRIX_FIELDS, report)
    evidence_rows = read_csv(root, EVIDENCE, EVIDENCE_FIELDS, report, EVIDENCE_OPTIONAL)
    risk_rows = read_csv(root, RISKS, RISK_FIELDS, report)
    signoff_rows = read_csv(root, SIGNOFFS, SIGNOFF_FIELDS, report, SIGNOFF_OPTIONAL)
    revalidation_rows = read_csv(root, REVALIDATION, REVALIDATION_FIELDS, report, REVALIDATION_OPTIONAL)
    matrix_by_id = unique_ids(matrix_rows, 'control_id', 'Verification matrix', report)
    evidence_by_id = unique_ids(evidence_rows, 'evidence_id', 'Evidence register', report)
    risks_by_id = unique_ids(risk_rows, 'risk_id', 'Risk register', report)
    today = today or dt.date.today()
    if not risk_rows:
        report.error('The risk register is empty; a release-assurance register cannot be valid with no risks. Retiring baseline risks needs an explicit governance decision, not deletion.')

    # Validate risks and evidence records.
    for risk_id, risk in risks_by_id.items():
        ctx = f'Risk {risk_id} line {risk.get("__line__", "?")}'
        if risk.get('status') not in RISK_STATUSES:
            report.error(f'{ctx}: invalid status {risk.get("status")!r}')
        if risk.get('inherent_severity') not in RISK_TIERS:
            report.error(f'{ctx}: invalid inherent_severity {risk.get("inherent_severity")!r}')
        for control_id in linked_controls(risk):
            if control_id not in matrix_by_id:
                report.error(f'{ctx}: linked control does not exist: {control_id}')
        if risk.get('status') == 'ACCEPTED':
            if not risk.get('accepted_by') or not risk.get('notes'):
                report.error(f'{ctx}: ACCEPTED risk requires accepted_by and rationale in notes')
            acceptance_ev = evidence_by_id.get(risk.get('acceptance_evidence_id', ''))
            if not acceptance_ev or acceptance_ev.get('status') != 'ACCEPTED':
                report.error(f'{ctx}: ACCEPTED risk requires an acceptance_evidence_id linked to ACCEPTED evidence')
            elif acceptance_ev.get('control_id') not in linked_controls(risk):
                report.error(f'{ctx}: acceptance evidence {acceptance_ev.get("evidence_id")} is not linked to the risk\'s controls ({risk.get("linked_controls") or "none"})')
            expiry = date_value(risk.get('expires_on', ''))
            if expiry is None:
                report.error(f'{ctx}: ACCEPTED risk requires expires_on in YYYY-MM-DD form')
            elif expiry < today:
                report.error(f'{ctx}: accepted risk expired on {expiry.isoformat()}')
        if risk.get('status') == 'CLOSED':
            closure_ev = evidence_by_id.get(risk.get('closure_evidence_id', ''))
            if not linked_controls(risk):
                report.error(f'{ctx}: CLOSED risk requires linked_controls so closure evidence can be tied to the risk')
            if not closure_ev or closure_ev.get('status') != 'ACCEPTED':
                report.error(f'{ctx}: CLOSED risk requires closure_evidence_id linked to ACCEPTED evidence')
            elif linked_controls(risk) and closure_ev.get('control_id') not in linked_controls(risk):
                report.error(f'{ctx}: closure evidence {closure_ev.get("evidence_id")} (control {closure_ev.get("control_id")}) is not linked to the risk\'s controls ({risk.get("linked_controls")})')

    for evidence_id, ev in evidence_by_id.items():
        ctx = f'Evidence {evidence_id} line {ev.get("__line__", "?")}'
        if ev.get('control_id') not in matrix_by_id:
            report.error(f'{ctx}: control_id does not exist: {ev.get("control_id", "")}')
        if ev.get('status') not in EVIDENCE_STATUSES:
            report.error(f'{ctx}: invalid status {ev.get("status")!r}')
        if ev.get('status') in {'COLLECTED', 'REVIEWED', 'ACCEPTED'}:
            p = artifact_path(root, ev.get('artifact_path', ''), report, ctx, required=True)
            if p and ev.get('artifact_sha256'):
                digest = hashlib.sha256(p.read_bytes()).hexdigest()
                if digest.lower() != ev['artifact_sha256'].lower():
                    report.error(f'{ctx}: SHA-256 mismatch for {ev.get("artifact_path")}')
        if ev.get('artifact_sha256') and not re.fullmatch(r'[0-9a-fA-F]{64}', ev['artifact_sha256']):
            report.error(f'{ctx}: artifact_sha256 must contain exactly 64 hexadecimal characters')
        if ev.get('commit_sha') and not HEX_COMMIT.fullmatch(ev['commit_sha']):
            report.error(f'{ctx}: commit_sha must be a full 40- or 64-character hexadecimal commit id')
        if ev.get('artifact_digest') and not HEX_SHA256.fullmatch(ev['artifact_digest']):
            report.error(f'{ctx}: artifact_digest must be exactly 64 hexadecimal characters')
        if ev.get('status') in {'REVIEWED', 'ACCEPTED'} and not ev.get('reviewed_by'):
            report.error(f'{ctx}: {ev.get("status")} evidence requires reviewed_by')
        if ev.get('status') == 'ACCEPTED':
            if not ev.get('created_by') or not ev.get('created_utc'):
                report.error(f'{ctx}: ACCEPTED evidence requires created_by and created_utc')
            elif not valid_timestamp(ev.get('created_utc', '')):
                report.error(f'{ctx}: created_utc must be an ISO-8601 timestamp with timezone, e.g. 2026-10-10T12:00:00Z')
            if not ev.get('artifact_sha256'):
                report.error(f'{ctx}: ACCEPTED evidence requires a SHA-256 hash')
            if not ev.get('valid_until'):
                report.error(f'{ctx}: ACCEPTED evidence requires valid_until')
            if not ev.get('approved_by'):
                report.error(f'{ctx}: ACCEPTED evidence requires approved_by')
            if ev.get('created_by') and ev.get('reviewed_by') and ev['created_by'] == ev['reviewed_by']:
                report.error(f'{ctx}: creator and reviewer must differ for accepted evidence')
            valid_until = date_value(ev.get('valid_until', ''))
            if ev.get('valid_until') and valid_until is None:
                report.error(f'{ctx}: valid_until must be YYYY-MM-DD')
            elif valid_until and valid_until < today:
                report.error(f'{ctx}: evidence expired on {valid_until.isoformat()}')
            created = parse_timestamp(ev.get('created_utc', ''))
            if valid_until and created and valid_until < created.astimezone(dt.timezone.utc).date():
                report.error(f'{ctx}: valid_until precedes created_utc')

    # Validate matrix fields/status/evidence links.
    for control_id, row in matrix_by_id.items():
        ctx = f'Control {control_id} line {row.get("__line__", "?")}'
        if not re.fullmatch(r'VFY-[A-Z0-9]+-[0-9]{3}', control_id):
            report.error(f'{ctx}: expected control ID format VFY-AREA-NNN')
        if row.get('risk_tier') not in RISK_TIERS:
            report.error(f'{ctx}: invalid risk_tier {row.get("risk_tier")!r}')
        if row.get('required_gate') not in GATES:
            report.error(f'{ctx}: invalid required_gate {row.get("required_gate")!r}')
        if row.get('status') not in CONTROL_STATUSES:
            report.error(f'{ctx}: invalid status {row.get("status")!r}')
        for required in ['domain','title','requirement','verification_method','acceptance_criteria','owner_role','frequency']:
            if not row.get(required):
                report.error(f'{ctx}: required field {required} is empty')
        evidence_id = row.get('evidence_id', '')
        ev = evidence_by_id.get(evidence_id) if evidence_id else None
        if evidence_id and not ev:
            report.error(f'{ctx}: evidence_id {evidence_id!r} not found in evidence register')
        if ev and ev.get('control_id') != control_id:
            report.error(f'{ctx}: evidence {evidence_id} belongs to control {ev.get("control_id")}, not {control_id}')
        if row.get('status') == 'PASS':
            if not ev or ev.get('status') not in {'REVIEWED', 'ACCEPTED'}:
                report.error(f'{ctx}: PASS requires linked REVIEWED or ACCEPTED evidence')
        if row.get('status') == 'NOT_APPLICABLE':
            if not row.get('notes') or not ev or ev.get('status') != 'ACCEPTED':
                report.error(f'{ctx}: NOT_APPLICABLE requires a reason in notes and ACCEPTED evidence')
        if row.get('status') == 'ACCEPTED_RISK':
            if not row.get('notes'):
                report.error(f'{ctx}: ACCEPTED_RISK requires rationale/compensating controls in notes')
            linked = [r for r in risks_by_id.values() if control_id in [x.strip() for x in r.get('linked_controls','').split(';') if x.strip()] and valid_accepted_risk(r, today, evidence_by_id)]
            if not linked:
                report.error(f'{ctx}: ACCEPTED_RISK requires a linked risk record accepted by an owner and not expired')
        if row.get('status') == 'FAIL' and row.get('risk_tier') == 'CRITICAL':
            report.warn(f'{ctx}: Critical control FAIL is a release stop')
        if gate is not None and row.get('required_gate') in GATES and GATES.index(row['required_gate']) <= GATES.index(gate):
            status = row.get('status')
            if status not in {'PASS', 'NOT_APPLICABLE', 'ACCEPTED_RISK'}:
                report.error(f'Gate {gate}: {control_id} is due by {row["required_gate"]} but status is {status}')
            if status == 'ACCEPTED_RISK' and row.get('risk_tier') == 'CRITICAL':
                report.error(f'Gate {gate}: critical control {control_id} cannot pass via ACCEPTED_RISK')
            if status == 'PASS' and (not ev or ev.get('status') != 'ACCEPTED'):
                report.error(f'Gate {gate}: {control_id} requires ACCEPTED evidence, not merely a test pass/review')
            if status == 'NOT_APPLICABLE' and (not ev or ev.get('status') != 'ACCEPTED'):
                report.error(f'Gate {gate}: {control_id} N/A rationale must have ACCEPTED evidence')

    # Production authorization (G4): a complete, time-bounded, release-bound sign-off with bound evidence.
    # --release-id narrows the evaluation to one release candidate; without it every production APPROVE row must hold.
    if gate == 'G4':
        valid_signoff = False
        for s in production_approvals(signoff_rows, release_id):
            before = len(report.errors)
            prefix = 'Gate G4: '
            if check_g4_signoff(root, s, report, today, prefix):
                check_bound_control_evidence(matrix_by_id, evidence_by_id, s, 'G4', report, historical=False)
            if len(report.errors) == before:
                valid_signoff = True
        if not valid_signoff:
            report.error('Gate G4: no complete, current APPROVE sign-off row for environment=production exists in RELEASE-SIGNOFF.csv')

    # G5 is an operational continuation/revalidation decision. It requires, and never replaces, a prior G4 production
    # approval for the same release, and it examines one dated operating period.
    if gate == 'G5':
        matches = [r for r in revalidation_rows if r.get('environment', '').lower() == 'production' and r.get('decision') == 'CONTINUE'
                   and (release_id is None or r.get('release_id') == release_id)]
        valid_revalidation = False
        for row in matches:
            ctx = f'Operational revalidation {row.get("period_id", "")}'
            before = len(report.errors)
            required = ['period_id', 'release_id', 'period_start', 'period_end', 'operations_reviewer', 'security_reviewer', 'clinical_reviewer', 'privacy_legal_reviewer', 'evidence_id', 'next_review', 'notes']
            missing = [f for f in required if not row.get(f)]
            if missing:
                report.error(f'{ctx}: missing fields: {", ".join(missing)}')
                continue
            dates = {}
            for field in ('period_start', 'period_end', 'next_review'):
                dates[field] = date_value(row[field])
                if dates[field] is None:
                    report.error(f'{ctx}: {field} must be YYYY-MM-DD (a real calendar date, nothing appended)')
            if None in dates.values():
                continue
            if dates['period_start'] > dates['period_end']:
                report.error(f'{ctx}: period_start is after period_end')
                continue
            if dates['period_end'] > today:
                report.error(f'{ctx}: period_end is in the future; an operating period cannot be revalidated before it ends')
            if dates['next_review'] <= dates['period_end']:
                report.error(f'{ctx}: next_review must be after period_end')
            elif dates['next_review'] < today:
                report.error(f'{ctx}: next_review is in the past; the revalidation has lapsed')
            names = [row.get(f, '').strip() for f in ['operations_reviewer', 'security_reviewer', 'clinical_reviewer', 'privacy_legal_reviewer']]
            if len(set(names)) != len(names):
                report.error(f'{ctx}: operational reviewers must be independent under this conservative default')
            # Prior G4 production approval for the same release, valid on the first day of the period.
            chosen = None
            candidate_errors: list[str] = []
            for s in production_approvals(signoff_rows, row['release_id']):
                scratch = Report()
                if check_g4_signoff(root, s, scratch, today, f'{ctx}: referenced G4 approval: ', as_of=dates['period_start']):
                    check_bound_control_evidence(matrix_by_id, evidence_by_id, s, 'G5', scratch, historical=True)
                if scratch.errors:
                    candidate_errors.extend(scratch.errors)
                elif chosen is None:
                    chosen = s
            if chosen is None:
                for message in candidate_errors:
                    report.error(message)
                report.error(f'{ctx}: no valid production G4 approval for release {row["release_id"]!r} that predates and covers period_start exists in RELEASE-SIGNOFF.csv')
            ev = evidence_by_id.get(row['evidence_id'])
            if not ev or ev.get('status') != 'ACCEPTED':
                report.error(f'{ctx}: requires linked ACCEPTED evidence')
            else:
                control = matrix_by_id.get(ev.get('control_id', ''))
                if not control or control.get('required_gate') != 'G5':
                    report.error(f'{ctx}: evidence {ev.get("evidence_id")} is not a G5 control evidence record (control {ev.get("control_id")})')
                if chosen is not None:
                    check_evidence_binding(ev, chosen, f'{ctx}: evidence {ev.get("evidence_id")}', report, historical=True)
                created = parse_timestamp(ev.get('created_utc', ''))
                if created and created.astimezone(dt.timezone.utc).date() < dates['period_start']:
                    report.error(f'{ctx}: evidence {ev.get("evidence_id")} was created before period_start, so it cannot describe this operating period')
            if len(report.errors) == before:
                valid_revalidation = True
        if not valid_revalidation:
            report.error('Gate G5: no complete, current production operational-revalidation row with decision=CONTINUE, a prior G4 approval for the same release, and accepted release-bound evidence exists in OPERATIONAL-REVALIDATION.csv')

    # Risk register participates in release decisions; it is not a passive list.
    if gate in {'G3', 'G4', 'G5'}:
        for risk_id, risk in risks_by_id.items():
            severity = risk.get('inherent_severity')
            status = risk.get('status')
            if severity == 'CRITICAL' and status != 'CLOSED':
                report.error(f'Gate {gate}: Critical risk {risk_id} must be CLOSED; this default gate does not permit critical-risk acceptance')
            elif severity == 'HIGH' and status in {'OPEN', 'IN_TREATMENT'}:
                report.error(f'Gate {gate}: High risk {risk_id} remains {status}; close it or record valid time-bounded authorized acceptance')

    check_markdown_links(root, report)
    if gate is None:
        report.warn('Structural validation does NOT prove the product is implemented, secure, clinically safe, compliant, or production ready.')
    else:
        report.ok(f'Readiness gate {gate} evaluated fail-closed. A pass applies only to the recorded scope/build and current evidence.')
    return report

def main() -> int:
    parser = argparse.ArgumentParser(description='Validate ARGON assurance registers; optionally evaluate a fail-closed readiness gate.')
    parser.add_argument('--root', default='.', help='Repository root (default: current directory)')
    parser.add_argument('--gate', choices=GATES, help='Evaluate readiness through this gate; incomplete records intentionally fail')
    parser.add_argument('--release-id', help='Evaluate G4/G5 for this release candidate only (default: every production approval/continuation row must hold)')
    parser.add_argument('--json-out', help='Write machine-readable report to this path')
    args = parser.parse_args()
    root = Path(args.root).resolve()
    if not root.is_dir():
        print(f'ERROR: root is not a directory: {root}', file=sys.stderr)
        return 2
    report = validate(root, args.gate, release_id=args.release_id)
    for msg in report.errors: print(f'ERROR: {msg}')
    for msg in report.warnings: print(f'WARNING: {msg}')
    for msg in report.info: print(f'OK: {msg}')
    if args.json_out:
        out = Path(args.json_out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(report.as_dict(), indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
        print(f'Report written: {out}')
    print(f'RESULT: {"PASS" if report.passed else "FAIL"} | errors={len(report.errors)} warnings={len(report.warnings)}')
    return 0 if report.passed else 1

if __name__ == '__main__':
    raise SystemExit(main())
