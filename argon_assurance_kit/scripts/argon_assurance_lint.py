#!/usr/bin/env python3
"""Validate ARGON assurance registers and fail closed when a readiness gate is requested.

This checks the assurance-pack bookkeeping. It does not test the ARGON application,
perform legal review, conduct a penetration test, or certify clinical safety/compliance.
Python standard library only.
"""
from __future__ import annotations
import argparse
import csv
import datetime as dt
import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Any

MATRIX = Path('docs/assurance/VERIFICATION-MATRIX.csv')
EVIDENCE = Path('docs/assurance/EVIDENCE-REGISTER.csv')
RISKS = Path('docs/assurance/RISK-REGISTER.csv')
SIGNOFFS = Path('docs/assurance/RELEASE-SIGNOFF.csv')
REVALIDATION = Path('docs/assurance/OPERATIONAL-REVALIDATION.csv')
GATES = ['G0', 'G1', 'G2', 'G3', 'G4', 'G5']
CONTROL_STATUSES = {'NOT_RUN', 'IN_PROGRESS', 'PASS', 'FAIL', 'BLOCKED', 'NOT_APPLICABLE', 'ACCEPTED_RISK'}
EVIDENCE_STATUSES = {'PLANNED', 'COLLECTED', 'REVIEWED', 'ACCEPTED', 'EXPIRED', 'REJECTED'}
RISK_STATUSES = {'OPEN', 'IN_TREATMENT', 'ACCEPTED', 'CLOSED'}
RISK_TIERS = {'CRITICAL', 'HIGH', 'MEDIUM', 'LOW'}
MATRIX_FIELDS = ['control_id','domain','title','requirement','verification_method','acceptance_criteria','risk_tier','required_gate','owner_role','frequency','status','evidence_id','notes']
EVIDENCE_FIELDS = ['evidence_id','control_id','artifact_path','artifact_sha256','evidence_type','created_by','reviewed_by','approved_by','created_utc','valid_until','status','notes']
RISK_FIELDS = ['risk_id','title','domain','scenario','impact','likelihood','inherent_severity','mitigation','owner_role','status','linked_controls','accepted_by','expires_on','acceptance_evidence_id','closure_evidence_id','notes']
SIGNOFF_FIELDS = ['release_id','environment','gate','decision','decision_owner','commit_sha','artifact_digest','configuration_version','migration_version','scope','rollback_plan_path','qa_signoff','security_signoff','clinical_signoff','privacy_legal_signoff','operations_signoff','recorded_utc','valid_until','notes']
REVALIDATION_FIELDS = ['period_id','environment','period_start','period_end','decision','operations_reviewer','security_reviewer','clinical_reviewer','privacy_legal_reviewer','evidence_id','next_review','notes']

class Report:
    def __init__(self) -> None:
        self.errors: list[str] = []
        self.warnings: list[str] = []
        self.info: list[str] = []
    def error(self, message: str) -> None: self.errors.append(message)
    def warn(self, message: str) -> None: self.warnings.append(message)
    def ok(self, message: str) -> None: self.info.append(message)
    @property
    def passed(self) -> bool: return not self.errors
    def as_dict(self) -> dict[str, Any]:
        return {'checker':'ARGON assurance-pack structural/readiness checker','scope_warning':'A passing structural check is not verification of the ARGON product.', 'passed':self.passed,'error_count':len(self.errors),'warning_count':len(self.warnings),'errors':self.errors,'warnings':self.warnings,'info':self.info}

def read_csv(root: Path, relative: Path, required_fields: list[str], report: Report) -> list[dict[str, str]]:
    path = root / relative
    if not path.is_file():
        report.error(f'Missing required register: {relative.as_posix()}')
        return []
    try:
        with path.open('r', newline='', encoding='utf-8-sig') as f:
            reader = csv.DictReader(f)
            fields = reader.fieldnames or []
            missing = [field for field in required_fields if field not in fields]
            if missing:
                report.error(f'{relative.as_posix()}: missing CSV columns: {", ".join(missing)}')
                return []
            rows = []
            for line, row in enumerate(reader, start=2):
                # Normalize None values generated by malformed trailing delimiters.
                clean = {k: (v or '').strip() for k, v in row.items() if k is not None}
                if not any(clean.values()):
                    continue
                clean['__line__'] = str(line)
                rows.append(clean)
            report.ok(f'{relative.as_posix()}: read {len(rows)} data row(s)')
            return rows
    except (OSError, UnicodeError, csv.Error) as exc:
        report.error(f'{relative.as_posix()}: cannot read CSV: {exc}')
        return []

def unique_ids(rows: list[dict[str, str]], key: str, label: str, report: Report) -> dict[str, dict[str, str]]:
    result: dict[str, dict[str, str]] = {}
    for row in rows:
        value = row.get(key, '').strip()
        line = row.get('__line__', '?')
        if not value:
            report.error(f'{label} line {line}: empty {key}')
        elif value in result:
            report.error(f'{label} line {line}: duplicate {key} {value!r} (first at line {result[value].get("__line__", "?")})')
        else:
            result[value] = row
    return result

def date_value(value: str) -> dt.date | None:
    if not value:
        return None
    try:
        return dt.date.fromisoformat(value[:10])
    except ValueError:
        return None

def valid_timestamp(value: str) -> bool:
    if not value:
        return False
    try:
        parsed = dt.datetime.fromisoformat(value.replace('Z', '+00:00'))
        return parsed.tzinfo is not None and parsed.utcoffset() is not None
    except ValueError:
        return False

def artifact_path(root: Path, raw: str, report: Report, context: str, required: bool) -> Path | None:
    if not raw:
        if required:
            report.error(f'{context}: artifact_path is required for this evidence state')
        return None
    p = Path(raw)
    if p.is_absolute():
        report.error(f'{context}: artifact_path must be repository-relative, not absolute')
        return None
    candidate = (root / p).resolve()
    root_resolved = root.resolve()
    try:
        candidate.relative_to(root_resolved)
    except ValueError:
        report.error(f'{context}: artifact_path escapes repository root')
        return None
    if required and not candidate.is_file():
        report.error(f'{context}: artifact file does not exist: {raw}')
        return None
    return candidate

def check_markdown_links(root: Path, report: Report) -> None:
    base = root / 'docs/assurance'
    if not base.is_dir():
        return
    pattern = re.compile(r'\[[^\]]*\]\(([^)]+)\)')
    count = 0
    for md in base.rglob('*.md'):
        try:
            text = md.read_text(encoding='utf-8')
        except (OSError, UnicodeError) as exc:
            report.error(f'{md.relative_to(root)}: cannot read Markdown: {exc}')
            continue
        for raw_target in pattern.findall(text):
            target = raw_target.strip().split()[0].strip('<>')
            if not target or target.startswith(('#', 'http://', 'https://', 'mailto:', 'tel:')):
                continue
            target = target.split('#', 1)[0]
            if not target:
                continue
            count += 1
            candidate = (md.parent / target).resolve()
            try:
                candidate.relative_to(root.resolve())
            except ValueError:
                report.error(f'{md.relative_to(root)}: local link escapes repository: {raw_target}')
                continue
            if not candidate.exists():
                report.error(f'{md.relative_to(root)}: broken local link: {raw_target}')
    report.ok(f'Checked {count} local Markdown link(s) under docs/assurance')

def valid_accepted_risk(risk: dict[str, str] | None, today: dt.date, evidence_by_id: dict[str, dict[str, str]]) -> bool:
    if not risk or risk.get('status') != 'ACCEPTED' or not risk.get('accepted_by'):
        return False
    expiry = date_value(risk.get('expires_on', ''))
    evidence = evidence_by_id.get(risk.get('acceptance_evidence_id', ''))
    return expiry is not None and expiry >= today and bool(evidence) and evidence.get('status') == 'ACCEPTED'

def validate(root: Path, gate: str | None = None) -> Report:
    report = Report()
    matrix_rows = read_csv(root, MATRIX, MATRIX_FIELDS, report)
    evidence_rows = read_csv(root, EVIDENCE, EVIDENCE_FIELDS, report)
    risk_rows = read_csv(root, RISKS, RISK_FIELDS, report)
    signoff_rows = read_csv(root, SIGNOFFS, SIGNOFF_FIELDS, report)
    revalidation_rows = read_csv(root, REVALIDATION, REVALIDATION_FIELDS, report)
    matrix_by_id = unique_ids(matrix_rows, 'control_id', 'Verification matrix', report)
    evidence_by_id = unique_ids(evidence_rows, 'evidence_id', 'Evidence register', report)
    risks_by_id = unique_ids(risk_rows, 'risk_id', 'Risk register', report)
    today = dt.date.today()

    # Validate risks and evidence records.
    for risk_id, risk in risks_by_id.items():
        ctx = f'Risk {risk_id} line {risk.get("__line__", "?")}'
        if risk.get('status') not in RISK_STATUSES:
            report.error(f'{ctx}: invalid status {risk.get("status")!r}')
        if risk.get('inherent_severity') not in RISK_TIERS:
            report.error(f'{ctx}: invalid inherent_severity {risk.get("inherent_severity")!r}')
        for control_id in [x.strip() for x in risk.get('linked_controls', '').split(';') if x.strip()]:
            if control_id not in matrix_by_id:
                report.error(f'{ctx}: linked control does not exist: {control_id}')
        if risk.get('status') == 'ACCEPTED':
            if not risk.get('accepted_by') or not risk.get('notes'):
                report.error(f'{ctx}: ACCEPTED risk requires accepted_by and rationale in notes')
            acceptance_ev = evidence_by_id.get(risk.get('acceptance_evidence_id', ''))
            if not acceptance_ev or acceptance_ev.get('status') != 'ACCEPTED':
                report.error(f'{ctx}: ACCEPTED risk requires an acceptance_evidence_id linked to ACCEPTED evidence')
            expiry = date_value(risk.get('expires_on', ''))
            if expiry is None:
                report.error(f'{ctx}: ACCEPTED risk requires expires_on in YYYY-MM-DD form')
            elif expiry < today:
                report.error(f'{ctx}: accepted risk expired on {expiry.isoformat()}')
        if risk.get('status') == 'CLOSED':
            closure_ev = evidence_by_id.get(risk.get('closure_evidence_id', ''))
            if not closure_ev or closure_ev.get('status') != 'ACCEPTED':
                report.error(f'{ctx}: CLOSED risk requires closure_evidence_id linked to ACCEPTED evidence')

    for evidence_id, ev in evidence_by_id.items():
        ctx = f'Evidence {evidence_id} line {ev.get("__line__", "?")}'
        if ev.get('control_id') not in matrix_by_id:
            report.error(f'{ctx}: control_id does not exist: {ev.get("control_id", "")}')
        if ev.get('status') not in EVIDENCE_STATUSES:
            report.error(f'{ctx}: invalid status {ev.get("status")!r}')
        if ev.get('status') in {'COLLECTED', 'REVIEWED', 'ACCEPTED'}:
            p = artifact_path(root, ev.get('artifact_path', ''), report, ctx, required=True)
            if p and ev.get('artifact_sha256'):
                digest = hashlib.sha256(p.read_bytes()).hexdigest()
                if digest.lower() != ev['artifact_sha256'].lower():
                    report.error(f'{ctx}: SHA-256 mismatch for {ev.get("artifact_path")}')
        if ev.get('artifact_sha256') and not re.fullmatch(r'[0-9a-fA-F]{64}', ev['artifact_sha256']):
            report.error(f'{ctx}: artifact_sha256 must contain exactly 64 hexadecimal characters')
        if ev.get('status') in {'REVIEWED', 'ACCEPTED'} and not ev.get('reviewed_by'):
            report.error(f'{ctx}: {ev.get("status")} evidence requires reviewed_by')
        if ev.get('status') == 'ACCEPTED':
            if not ev.get('created_by') or not ev.get('created_utc'):
                report.error(f'{ctx}: ACCEPTED evidence requires created_by and created_utc')
            elif not valid_timestamp(ev.get('created_utc', '')):
                report.error(f'{ctx}: created_utc must be an ISO-8601 timestamp with timezone, e.g. 2026-10-10T12:00:00Z')
            if not ev.get('artifact_sha256'):
                report.error(f'{ctx}: ACCEPTED evidence requires a SHA-256 hash')
            if not ev.get('valid_until'):
                report.error(f'{ctx}: ACCEPTED evidence requires valid_until')
            if not ev.get('approved_by'):
                report.error(f'{ctx}: ACCEPTED evidence requires approved_by')
            if ev.get('created_by') and ev.get('reviewed_by') and ev['created_by'] == ev['reviewed_by']:
                report.error(f'{ctx}: creator and reviewer must differ for accepted evidence')
            valid_until = date_value(ev.get('valid_until', ''))
            if ev.get('valid_until') and valid_until is None:
                report.error(f'{ctx}: valid_until must be YYYY-MM-DD')
            elif valid_until and valid_until < today:
                report.error(f'{ctx}: evidence expired on {valid_until.isoformat()}')

    # Validate matrix fields/status/evidence links.
    for control_id, row in matrix_by_id.items():
        ctx = f'Control {control_id} line {row.get("__line__", "?")}'
        if not re.fullmatch(r'VFY-[A-Z0-9]+-[0-9]{3}', control_id):
            report.error(f'{ctx}: expected control ID format VFY-AREA-NNN')
        if row.get('risk_tier') not in RISK_TIERS:
            report.error(f'{ctx}: invalid risk_tier {row.get("risk_tier")!r}')
        if row.get('required_gate') not in GATES:
            report.error(f'{ctx}: invalid required_gate {row.get("required_gate")!r}')
        if row.get('status') not in CONTROL_STATUSES:
            report.error(f'{ctx}: invalid status {row.get("status")!r}')
        for required in ['domain','title','requirement','verification_method','acceptance_criteria','owner_role','frequency']:
            if not row.get(required):
                report.error(f'{ctx}: required field {required} is empty')
        evidence_id = row.get('evidence_id', '')
        ev = evidence_by_id.get(evidence_id) if evidence_id else None
        if evidence_id and not ev:
            report.error(f'{ctx}: evidence_id {evidence_id!r} not found in evidence register')
        if ev and ev.get('control_id') != control_id:
            report.error(f'{ctx}: evidence {evidence_id} belongs to control {ev.get("control_id")}, not {control_id}')
        if row.get('status') == 'PASS':
            if not ev or ev.get('status') not in {'REVIEWED', 'ACCEPTED'}:
                report.error(f'{ctx}: PASS requires linked REVIEWED or ACCEPTED evidence')
        if row.get('status') == 'NOT_APPLICABLE':
            if not row.get('notes') or not ev or ev.get('status') != 'ACCEPTED':
                report.error(f'{ctx}: NOT_APPLICABLE requires a reason in notes and ACCEPTED evidence')
        if row.get('status') == 'ACCEPTED_RISK':
            if not row.get('notes'):
                report.error(f'{ctx}: ACCEPTED_RISK requires rationale/compensating controls in notes')
            linked = [r for r in risks_by_id.values() if control_id in [x.strip() for x in r.get('linked_controls','').split(';') if x.strip()] and valid_accepted_risk(r, today, evidence_by_id)]
            if not linked:
                report.error(f'{ctx}: ACCEPTED_RISK requires a linked risk record accepted by an owner and not expired')
        if row.get('status') == 'FAIL' and row.get('risk_tier') == 'CRITICAL':
            report.warn(f'{ctx}: Critical control FAIL is a release stop')
        if gate is not None and row.get('required_gate') in GATES and GATES.index(row['required_gate']) <= GATES.index(gate):
            status = row.get('status')
            if status not in {'PASS', 'NOT_APPLICABLE', 'ACCEPTED_RISK'}:
                report.error(f'Gate {gate}: {control_id} is due by {row["required_gate"]} but status is {status}')
            if status == 'ACCEPTED_RISK' and row.get('risk_tier') == 'CRITICAL':
                report.error(f'Gate {gate}: critical control {control_id} cannot pass via ACCEPTED_RISK')
            if status == 'PASS' and (not ev or ev.get('status') != 'ACCEPTED'):
                report.error(f'Gate {gate}: {control_id} requires ACCEPTED evidence, not merely a test pass/review')
            if status == 'NOT_APPLICABLE' and (not ev or ev.get('status') != 'ACCEPTED'):
                report.error(f'Gate {gate}: {control_id} N/A rationale must have ACCEPTED evidence')

    # Production authorization (G4) requires a complete, time-bounded sign-off.
    if gate == 'G4':
        matching = [s for s in signoff_rows if s.get('gate') == 'G4' and s.get('environment', '').lower() == 'production' and s.get('decision') == 'APPROVE']
        valid_signoff = None
        for s in matching:
            fields = ['release_id', 'decision_owner', 'commit_sha', 'artifact_digest', 'configuration_version', 'migration_version', 'scope', 'rollback_plan_path', 'qa_signoff', 'security_signoff', 'clinical_signoff', 'privacy_legal_signoff', 'operations_signoff', 'recorded_utc', 'valid_until']
            missing = [f for f in fields if not s.get(f)]
            expiry = date_value(s.get('valid_until', ''))
            if missing:
                report.error(f'Gate G4: production sign-off row is missing: {", ".join(missing)}')
                continue
            if expiry is None or expiry < today:
                report.error('Gate G4: production sign-off is expired or has invalid valid_until')
                continue
            if not valid_timestamp(s.get('recorded_utc', '')):
                report.error('Gate G4: recorded_utc must be ISO-8601 with timezone')
                continue
            artifact = artifact_path(root, s.get('rollback_plan_path', ''), report, 'Gate G4 rollback plan', required=True)
            if artifact is None:
                continue
                continue
            names = [s.get(f, '').strip() for f in ['decision_owner', 'qa_signoff', 'security_signoff', 'clinical_signoff', 'privacy_legal_signoff', 'operations_signoff']]
            if len(set(names)) != len(names):
                report.error('Gate G4: decision owner and signers must be distinct under this conservative default; change only through approved governance')
                continue
            valid_signoff = s
        if not valid_signoff:
            report.error('Gate G4: no complete, current APPROVE sign-off row for environment=production exists in RELEASE-SIGNOFF.csv')

    # G5 is an operational continuation/revalidation decision, not a reused release approval.
    if gate == 'G5':
        matches = [r for r in revalidation_rows if r.get('environment', '').lower() == 'production' and r.get('decision') == 'CONTINUE']
        valid_revalidation = False
        for row in matches:
            ctx = f'Operational revalidation {row.get("period_id", "")}'
            required = ['period_id', 'period_start', 'period_end', 'operations_reviewer', 'security_reviewer', 'clinical_reviewer', 'privacy_legal_reviewer', 'evidence_id', 'next_review', 'notes']
            missing = [f for f in required if not row.get(f)]
            if missing:
                report.error(f'{ctx}: missing fields: {", ".join(missing)}')
                continue
            ev = evidence_by_id.get(row.get('evidence_id', ''))
            if not ev or ev.get('status') != 'ACCEPTED':
                report.error(f'{ctx}: requires linked ACCEPTED evidence')
                continue
            names = [row.get(f, '').strip() for f in ['operations_reviewer', 'security_reviewer', 'clinical_reviewer', 'privacy_legal_reviewer']]
            if len(set(names)) != len(names):
                report.error(f'{ctx}: operational reviewers must be independent under this conservative default')
                continue
            next_review = date_value(row.get('next_review', ''))
            if next_review is None or next_review < today:
                report.error(f'{ctx}: next_review must be a current/future YYYY-MM-DD date')
                continue
            valid_revalidation = True
        if not valid_revalidation:
            report.error('Gate G5: no complete, current production operational-revalidation row with decision=CONTINUE and accepted evidence exists in OPERATIONAL-REVALIDATION.csv')

    # Risk register participates in release decisions; it is not a passive list.
    if gate in {'G3', 'G4', 'G5'}:
        for risk_id, risk in risks_by_id.items():
            severity = risk.get('inherent_severity')
            status = risk.get('status')
            if severity == 'CRITICAL' and status != 'CLOSED':
                report.error(f'Gate {gate}: Critical risk {risk_id} must be CLOSED; this default gate does not permit critical-risk acceptance')
            elif severity == 'HIGH' and status in {'OPEN', 'IN_TREATMENT'}:
                report.error(f'Gate {gate}: High risk {risk_id} remains {status}; close it or record valid time-bounded authorized acceptance')

    check_markdown_links(root, report)
    if gate is None:
        report.warn('Structural validation does NOT prove the product is implemented, secure, clinically safe, compliant, or production ready.')
    else:
        report.ok(f'Readiness gate {gate} evaluated fail-closed. A pass applies only to the recorded scope/build and current evidence.')
    return report

def main() -> int:
    parser = argparse.ArgumentParser(description='Validate ARGON assurance registers; optionally evaluate a fail-closed readiness gate.')
    parser.add_argument('--root', default='.', help='Repository root (default: current directory)')
    parser.add_argument('--gate', choices=GATES, help='Evaluate readiness through this gate; incomplete records intentionally fail')
    parser.add_argument('--json-out', help='Write machine-readable report to this path')
    args = parser.parse_args()
    root = Path(args.root).resolve()
    if not root.is_dir():
        print(f'ERROR: root is not a directory: {root}', file=sys.stderr)
        return 2
    report = validate(root, args.gate)
    for msg in report.errors: print(f'ERROR: {msg}')
    for msg in report.warnings: print(f'WARNING: {msg}')
    for msg in report.info: print(f'OK: {msg}')
    if args.json_out:
        out = Path(args.json_out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(report.as_dict(), indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
        print(f'Report written: {out}')
    print(f'RESULT: {"PASS" if report.passed else "FAIL"} | errors={len(report.errors)} warnings={len(report.warnings)}')
    return 0 if report.passed else 1

if __name__ == '__main__':
    raise SystemExit(main())
